const PT = ["ทั้งหมด","ใบ","ลำต้น","ราก","ผล","ทั้งต้น"];
let cur = "ทั้งหมด";

function renderDiseases() {
  const q = (document.getElementById("dq")?.value || "").trim();
  let output = "";
  D.forEach(d => {
    const ok = (cur === "ทั้งหมด" || d[2].split(" ").includes(cur)) && (!q || (d[0] + d[3] + d[4]).includes(q));
    if (!ok) return;
    output += `<details class="dz"><summary><span>${d[0]}</span><em>${d[1]}</em></summary><div class="db"><p><b>อาการ</b>${d[3]}</p><p><b>สาเหตุ</b>${d[4]}</p><div class="m1"><h4>1. วิธีที่ไม่ใช้สารเคมี (เริ่มที่นี่)</h4><ul>${d[5].split("|").map(x => `<li>${x}</li>`).join("")}</ul></div><div class="m2"><h4>2. วิธีที่ใช้สารเคมี (เมื่อวิธีแรกไม่พอ)</h4><p>${d[6]}</p></div></div></details>`;
  });
  document.getElementById("dlist").innerHTML = output || '<p class="empty">ไม่พบรายการที่ตรงกัน ลองใช้คำอื่น หรือเลือกส่วนของพืชที่พบอาการ</p>';
}

function renderChips() {
  const chips = document.getElementById("chips");
  chips.innerHTML = PT.map(p => `<button class="chip" type="button" aria-pressed="${p === cur}" data-p="${p}">${p}</button>`).join("");
  chips.querySelectorAll("button").forEach(btn => {
    btn.onclick = () => {
      cur = btn.getAttribute("data-p");
      renderChips();
      renderDiseases();
    };
  });
}

